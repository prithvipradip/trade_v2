def gen_risk_ceilings() -> str:
    rows = []
    for dotted, text in CEILINGS:
        shipped = _shipped(dotted)
        shown = num(shipped) if shipped is not None else "null (= risk.max_position_risk_pct)"
        rows.append([f"`{dotted}`", shown, _range(dotted), text])
    return NOTE.format(src="ait/config/settings.py bounds and config.yaml") + "\n" + table(
        ["Setting", "Shipped value", "Allowed range", "What it bounds"], rows)


def gen_order_timeline() -> str:
    def block(title: str, spec) -> str:
        rows = []
        for age, what, keys in spec:
            rows.append([age, what, " / ".join(f"`{k}`" for k in keys),
                         " / ".join(num(_default(k)) for k in keys), " / ".join(_range(k) for k in keys)])
        return f"**{title}**\n\n" + table(["Age", "What happens", "Setting", "Default", "Allowed range"], rows)
    return (NOTE.format(src="ait/config/settings.py") + "\n" + block("Exit order (the position is CLOSING)", ORDER_EXIT) + "\n"
            + block("Entry order", ORDER_ENTRY))


def gen_supervisor_jobs() -> str:
    from ait.orchestration import master

    class Stub:
        def __init__(self):
            self.jobs: list[tuple[str, object]] = []

        def add_job(self, fn, trigger=None, **kw):
            self.jobs.append((kw.get("id") or getattr(fn, "__name__", "?"), trigger, kw))

    class _NoCollection:
        short_dte_enabled = False

    original = master._data_collection_cfg
    master._data_collection_cfg = lambda: _NoCollection()          # the optional job is documented separately
    try:
        s = Stub()
        master._register_recurring_jobs(s, bot=object(), web=object())
    finally:
        master._data_collection_cfg = original

    def when(trigger, kw) -> str:
        if trigger == "interval":
            return f"every {kw.get('minutes')} min"
        fields = {f.name: str(f) for f in trigger.fields}
        days = {"mon-fri": "Mon-Fri", "sun": "Sunday", "fri": "Friday", "*": "daily"}.get(fields.get("day_of_week", "*"), fields.get("day_of_week"))
        if fields.get("day", "*") != "*":
            days = f"day {fields['day']} of the month"
        return f"{days} {int(fields.get('hour', 0)):02d}:{int(fields.get('minute', 0)):02d} ET"

    rows = []
    for jid, trigger, kw in s.jobs:
        if jid not in JOB_TEXT:
            raise SystemExit(f"gen_docs: supervisor job {jid!r} has no entry in JOB_TEXT; add one so it is documented")
        name, what = JOB_TEXT[jid]
        rows.append([name, f"`{jid}`", when(trigger, kw), what])
    missing = set(JOB_TEXT) - {j for j, *_ in s.jobs}
    if missing:
        raise SystemExit(f"gen_docs: JOB_TEXT documents jobs the supervisor no longer registers: {sorted(missing)}")
    rows.append(["Short-DTE friction collection", "`short_dte_collection`", "optional, weekdays, time from `data_collection.short_dte_time_et`",
                 "Research data only; registered only when `data_collection.short_dte_enabled` is true; never touches orders"])
    return NOTE.format(src="ait/orchestration/master.py::_register_recurring_jobs") + "\n" + table(["Job", "Id", "When (ET)", "What it does"], rows)


def gen_go_live_gates() -> str:
    from ait.reporting import go_live as g
    values = {"GO_LIVE_PRELIM_CLOSES": g.GO_LIVE_PRELIM_CLOSES, "GO_LIVE_FUNDING_CLOSES": g.GO_LIVE_FUNDING_CLOSES, "GATE_PF": g.GATE_PF,
              "GATE_DD_PCT": g.GATE_DD_PCT, "GATE_SLIP_PCT": g.GATE_SLIP_PCT, "SLIP_WINDOW": g.SLIP_WINDOW}
    crit = []
    for label, what, rule in GO_LIVE_CRITERIA:
        for name in values:
            rule = re.sub(rf"`{name}`", f"`{name}` ({num(values[name])})", rule)
            what = re.sub(rf"`{name}`", f"`{name}` ({num(values[name])})", what)
        crit.append([label, what, rule])
    return NOTE.format(src="ait/reporting/go_live.py") + "\n" + table(["Criterion", "What is measured", "Passes when"], crit)


