def code_stamp(rel: str) -> str:
    """Fingerprint of a script's code: docstrings, blank lines and whole-line comments (REM / :: in .bat) do not count.

    Built from source lines, not from `ast.dump`, so it is the same on every Python version.
    """
    import ast
    import hashlib
    text = (ROOT / rel).read_text(errors="ignore")
    skip: set[int] = set()
    if rel.endswith(".py"):
        for node in ast.walk(ast.parse(text)):
            if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.body:
                first = node.body[0]
                if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
                    skip.update(range(first.lineno, (first.end_lineno or first.lineno) + 1))
    kept = []
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if n in skip or not s:
            continue
        if rel.endswith(".bat"):
            if s.upper().startswith("REM ") or s.upper() == "REM" or s.startswith("::"):
                continue
        elif s.startswith("#"):
            continue
        kept.append(s)
    return hashlib.sha1("\n".join(kept).encode()).hexdigest()[:12]


def _script_facts(rel: str) -> tuple[list[str], bool]:
    """(command-line flags, imports an IB client) read from the script's own code."""
    import ast
    if not rel.endswith(".py"):
        return [], False
    tree = ast.parse((ROOT / rel).read_text(errors="ignore"))
    flags: list[str] = []
    ib = False
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, "attr", "") == "add_argument":
            flags += [a.value for a in n.args if isinstance(a, ast.Constant) and isinstance(a.value, str) and a.value.startswith("-")]
        elif isinstance(n, ast.Import):
            ib |= any(a.name.split(".")[0] == "ib_insync" for a in n.names)
        elif isinstance(n, ast.ImportFrom) and n.module:
            ib |= n.module.split(".")[0] == "ib_insync" or n.module.startswith("ait.broker")
    return flags, ib


