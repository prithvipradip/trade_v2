def _first_doc_line(path: Path) -> str:
    import ast
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(errors="ignore")))
    except SyntaxError:
        return "-"
    if not doc:
        return "-"
    line = doc.strip().splitlines()[0].strip()
    line = re.sub(r"^\s*[WR]-[A-Za-z]+:\s*", "", line)               # "W-capital:" style tags
    line = _AUDIT_PAREN.sub("", strip_tag(line))
    line = _INLINE_TAG.sub("", line)
    line = re.sub(r"\(\s*\)", "", line)                                # parentheses left empty by the removals
    line = " ".join(line.replace("`", "").split()).rstrip(" :-,;")
    line = line[:1].upper() + line[1:]
    return (line[:150].rstrip() + "…") if len(line) > 150 else (line or "-")


