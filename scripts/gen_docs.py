def _check_catalogue(cat: dict[str, dict]) -> None:
    files = script_files()
    missing = [f for f in files if f not in cat]
    extra = [k for k in cat if k not in files]
    if missing or extra:
        raise SystemExit(f"gen_docs: scripts/script_catalogue.yaml is out of step with the scripts: no entry for {missing}; entry without a script {extra}")
    for rel in files:
        e = cat[rel]
        if set(e) != _CATALOGUE_FIELDS:
            raise SystemExit(f"gen_docs: {rel}: fields must be exactly {sorted(_CATALOGUE_FIELDS)}, got {sorted(e)}")
        if e["group"] not in SCRIPT_GROUPS:
            raise SystemExit(f"gen_docs: {rel}: unknown group {e['group']!r}")
        if e["needs_ib"] not in NEEDS_IB:
            raise SystemExit(f"gen_docs: {rel}: needs_ib must be one of {sorted(NEEDS_IB)}")
        _flags, imports_ib = _script_facts(rel)
        if imports_ib and e["needs_ib"] not in ("yes", "optional"):
            raise SystemExit(f"gen_docs: {rel} imports an IB client, so needs_ib cannot be {e['needs_ib']!r}")
        if not imports_ib and e["needs_ib"] in ("yes", "optional"):
            raise SystemExit(f"gen_docs: {rel} imports no IB client, so needs_ib cannot be {e['needs_ib']!r}")
        for field in ("what", "when", "writes", "example", "explained"):
            if not str(e[field]).strip():
                raise SystemExit(f"gen_docs: {rel}: {field} is empty")


