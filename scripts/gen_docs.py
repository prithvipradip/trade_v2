def _model_of(annotation):
    """The pydantic model class inside ``annotation`` (a plain model or an Optional of one), else None."""
    import typing
    from pydantic import BaseModel
    cands = [annotation] if isinstance(annotation, type) else []
    cands += [a for a in typing.get_args(annotation) if isinstance(a, type)]
    for c in cands:
        if issubclass(c, BaseModel):
            return c
    return None


