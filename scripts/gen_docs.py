def num(v) -> str:
    """A plain decimal, never scientific notation (the drift tests parse it with [0-9.]+)."""
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, int):
        return str(v)
    s = repr(float(v))
    return format(Decimal(s), "f") if "e" in s.lower() else s


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


_TAG = re.compile(r"^\s*(?:W\d+[a-z]?|R\d+[a-z]?)(?:\s*[/,&]\s*(?:W\d+[a-z]?|R\d+[a-z]?))*\b[^:]{0,40}:\s*")


def strip_tag(text: str) -> str:
    """Drop a leading provenance tag such as ``W97:`` or ``W52a (note):`` from a schema description."""
    prev = None
    while prev != text:
        prev, text = text, _TAG.sub("", text, count=1)
    return text.strip()


def first_sentence(text: str, limit: int = 260) -> str:
    text = strip_tag(" ".join(str(text).split()))
    m = re.search(r"(?<=[a-z0-9\)\]`])\.\s+(?=[A-Z(])", text)
    s = text[: m.start() + 1] if m else text
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def _bounds(model, field: str) -> tuple[float | None, float | None]:
    lo = hi = None
    for m in model.model_fields[field].metadata:
        lo = getattr(m, "ge", getattr(m, "gt", lo)) if (hasattr(m, "ge") or hasattr(m, "gt")) else lo
        hi = getattr(m, "le", getattr(m, "lt", hi)) if (hasattr(m, "le") or hasattr(m, "lt")) else hi
    return lo, hi


def _resolve(dotted: str):
    """(owning model class, field name) for ``section.key`` in the Settings schema."""
    from ait.config.settings import Settings
    model = Settings
    parts = dotted.split(".")
    for part in parts[:-1]:
        model = model.model_fields[part].annotation
    return model, parts[-1]


_RAW_YAML: dict[str, object] = {}


def _raw_yaml(name: str):
    """A config file parsed once per run (parsing it for each of the ~600 settings made a run take minutes)."""
    if name not in _RAW_YAML:
        _RAW_YAML[name] = yaml.safe_load((ROOT / name).read_text())
    return _RAW_YAML[name]


def _shipped(dotted: str):
    raw = _raw_yaml("config.yaml")
    for part in dotted.split("."):
        if not isinstance(raw, dict) or part not in raw:
            return None
        raw = raw[part]
    return raw


def _default(dotted: str):
    model, field = _resolve(dotted)
    return model.model_fields[field].default


def _range(dotted: str) -> str:
    lo, hi = _bounds(*_resolve(dotted))
    return f"{num(lo)} - {num(hi)}"


_HISTORY = re.compile(r"\s*[\(\[][^()\[\]]*\b(?:literal|was a|was the|Was a|Was the|W\d+[a-z]?|R\d+[a-z]?)\b[^()\[\]]*[\)\]]")
_LEAD_FINDING = re.compile(r"^\s*Finding [a-z0-9-]+:\s*")           # "Finding model-vs-reality-x: ..." audit prefix
_AUDIT_PAREN = re.compile(r"\s*[\(\[][^()\[\]]*\baudit\b[^()\[\]]*[\)\]]", re.I)      # "(audit 2026-07-07 item 3.3)"
_INLINE_TAG = re.compile(r"\b(?:W\d+[a-z]?|R\d+[a-z]?)\b[:,]?\s*")


def clean_desc(text: str, limit: int = 330, key: str | None = None) -> str:
    """One readable sentence from a schema description: provenance tags and history parentheticals removed.
    A hand-written MEANING entry for ``key`` wins."""
    if key in MEANING:
        return MEANING[key]
    text = " ".join(str(text or "").split())
    text = _LEAD_FINDING.sub("", text)
    text = _AUDIT_PAREN.sub("", text)
    text = _HISTORY.sub("", strip_tag(text))
    text = _INLINE_TAG.sub("", text)
    text = re.sub(r"\s+([,.;:])", r"\1", text)
    out = first_sentence(text, limit)
    return out[:1].upper() + out[1:]


def _field(dotted: str):
    model, name = _resolve(dotted)
    return model.model_fields[name]


def _shipped_research(dotted: str):
    raw = _raw_yaml("config_research.yaml")
    for part in dotted.split("."):
        if not isinstance(raw, dict) or part not in raw:
            return None
        raw = raw[part]
    return raw


def _effective(dotted: str, research: bool = False):
    """The value config.yaml ships for ``dotted``, else the schema default. ``research=True``: the research overlay's value wins."""
    if research:
        v = _shipped_research(dotted)
        if v is not None:
            return v
    shipped = _shipped(dotted)
    if shipped is not None:
        return shipped
    f = _field(dotted)
    return f.get_default(call_default_factory=True)


def show(v) -> str:
    if isinstance(v, bool) or v is None:
        return str(v).lower() if v is not None else "null"
    if isinstance(v, (int, float)):
        return num(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(show(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {show(x)}" for k, x in v.items()) + "}"
    return str(v)


def _range_or_dash(dotted: str) -> str:
    lo, hi = _bounds(*_resolve(dotted))
    if lo is None and hi is None:
        return "-"
    return f"{num(lo) if lo is not None else '..'} - {num(hi) if hi is not None else '..'}"


def settings_table(keys: list[str], src: str = "ait/config/settings.py and config.yaml", research: bool = False) -> str:
    rows = []
    for k in keys:
        f = _field(k)
        rows.append([f"`{k}`", show(_effective(k, research)), _range_or_dash(k), clean_desc(f.description, key=k) if (f.description or k in MEANING) else "-"])
    return NOTE.format(src=src) + "\n" + table(["Setting", "Value", "Allowed range", "Meaning"], rows)


def _fields_of(dotted_model: str, prefix: str = "") -> list[str]:
    """Every leaf field name under ``dotted_model`` (a section such as ``regime``), optionally filtered by name prefix."""
    from ait.config.settings import Settings
    model = Settings
    for part in dotted_model.split("."):
        model = model.model_fields[part].annotation
    return [f"{dotted_model}.{n}" for n, f in model.model_fields.items()
            if n.startswith(prefix) and getattr(f.annotation, "model_fields", None) is None]


