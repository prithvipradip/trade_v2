def render_documents() -> dict[Path, str]:
    """Every document containing generated blocks, with the blocks filled in."""
    out: dict[Path, str] = {}
    for path in sorted(DOCS.glob("*.md")):
        text = path.read_text()
        if "<!-- BEGIN GENERATED:" not in text:
            continue

        def fill(m: re.Match) -> str:
            name = m.group("name")
            if name not in GENERATORS:
                raise SystemExit(f"gen_docs: {path.name} has an unknown generated block {name!r}")
            body = GENERATORS[name]()
            return m.group(1) + body + m.group(4)
        out[path] = BLOCK.sub(fill, text)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated content is out of date (no writes)")
    ap.add_argument("--restamp", nargs="+", metavar="SCRIPT",
                    help="record the current code fingerprint of these scripts' catalogue entries. Only after re-reading each entry against the code")
    args = ap.parse_args(argv)
    if args.restamp:
        restamp(args.restamp)
        print(f"restamped {len(args.restamp)} entr{'y' if len(args.restamp) == 1 else 'ies'}")
        return 0
    targets = {**render_documents(), **generated_files()}
    stale = [p for p, new in targets.items() if not p.exists() or p.read_text() != new]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale:
            print("run: python scripts/gen_docs.py")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(targets[p])
        print(f"wrote {p.relative_to(ROOT)}")
    print("generated content is up to date" if not stale else f"{len(stale)} file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
