#!/usr/bin/env python
"""Generate the parts of docs/ that must equal the code, so they cannot go stale.

    python scripts/gen_docs.py            # rewrite every generated block / file
    python scripts/gen_docs.py --check    # exit 1 (and say which) if anything is out of date; no writes

Two kinds of output:

* **Blocks** inside hand-written documents, between ``<!-- BEGIN GENERATED: name -->`` and ``<!-- END GENERATED: name -->``.
  Everything between the markers is replaced. Edit the code (or the small prose tables at the top of this script), not the block.
* **Reference files** under ``docs/reference/`` (written whole): every setting in the schema.

A table row that needs prose the code does not carry (what a supervisor job does, what an order-timeline step does) takes that prose
from a dictionary in this file keyed by the code's own identifier; a new job or setting without an entry fails the run, which is how a
new item forces its documentation.

Needs the real ``config.yaml`` (for shipped values). Read-only against everything but ``docs/``.
"""
