             "(`yes`; `optional` = only for some options; `indirect` = it starts something that connects; `no`). "
             "**Writes** is the part to read before running anything. **Flags** are copied from the script's own argument parser "
             "(`-` means it takes none or reads them another way; run it with `--help` for the full list).", "",
             "Why a row changes: the **Flags** and **IB** columns are read from the code on every run, so they cannot drift. "
